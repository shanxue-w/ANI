function dudt = compound_ode(~, u)
    % 参数设置
    l1 = 1;
    l2 = 1;
    m1 = 1;
    m2 = 1;
    g  = 10;

    % 初始化导数向量
    dudt = zeros(4, 1);

    theta = u(1) - u(3);

    common = cos(theta)^2 - 2.0;
    cos_thetea = cos(theta);
    sin_theta  = sin(theta);

    dudt(1) = u(2);
    dudt(3) = u(4);

    dudt(2) = (...
        sin_theta*cos_thetea*u(2)^2 + ...
        sin_theta*u(4)^2 + ...
        20*sin(u(1)) - ...
        10*sin(u(3))*cos_thetea - ...
        0.1*cos_thetea*u(4) + ...
        0.1*u(2) ...
        ) / common;

    dudt(4) = (...
        -sin_theta*cos_thetea*u(4)^2 - ...
        2.0*sin_theta*u(2)^2 - ...
        20.0*sin(u(1))*cos_thetea + ...
        20.0*sin(u(3)) - ...
        0.1*cos_thetea*u(2) + ...
        0.2*u(4) ...
        ) / common;
    
end
